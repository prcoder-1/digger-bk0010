/ ============================================================================
/  Геймплейная фоновая музыка «Popcorn» и её процедура воспроизведения,
/  извлечённые из Digger.bin (сторонний BK-0010 порт, (C) SHW&AW 10.90).
/
/  Это ИМЕННО геймплейный проигрыватель (адрес 034600 в распакованном образе),
/  вызываемый в игровом цикле каждый проход, — НЕ блокирующий плеер «Lambada»
/  с заставки (04440). Мелодия — «Popcorn» (та же, что music1 «музыка движения»
/  в оригинальном PC-Digger): D4,C4,D4,A3,F3,A3,D3, … Данные сняты из
/  распакованного в ОЗУ образа через эмулятор БК и сверены дизассемблером.
/  Целевая машина — Электроника БК-0010(-01), КР1801ВМ1. Синтаксис — GNU as.
/
/  --- Устройство ---
/  Плеер трёхголосный (одновременно 3 меандра через один динамик 0177716),
/  но в данных «Popcorn» голоса 1,2 всегда пауза (077777), звучит только
/  голос 3 — фактически монофонично. Формат ноты — запись из 4 слов:
/     +0: длительность предыдущей ноты (служебное), +2: период голоса1,
/     +4: период голоса2, +6: период голоса3, длительность ноты — в +8
/     (= слово +0 следующей записи). 077777 = пауза (голос не переключается).
/     Терминатор — запись со словом +2 == 0 (плеер зацикливает мелодию).
/
/  music_tick() — проиграть ОДНУ ноту (на её длительность), продвинуть
/     указатель; в конце мелодии — сброс на начало. Сохраняет r0-r5.
/     Вызывается в свободное время в конце кадра (см. digger.c): за проход
/     играется одна нота, ноты идут встык, музыка звучит, не задерживая кадр.
/  music_start() — начать мелодию сначала.
/
/  Отличия от байтов оригинала: абсолютные адреса переменных/данных
/  (035022/035024 -> m_pptr/m_pdur/pop_data) и констант динамика
/  (0102064/0102076 -> spk_on/spk_off) перенесены в модуль; логика — как в
/  Digger.bin (034600).
/ ============================================================================

	.text
	.even
	.globl	_music_start, _music_tick

/ --- Начать мелодию сначала --- 
_music_start:
	mov	$pop_data, @$m_pptr
	rts	pc

/ --- Проиграть одну ноту «Popcorn» (ориг. 034600) ---
_music_tick:
	mov	r0, -(sp)
	mov	r1, -(sp)
	mov	r2, -(sp)
	mov	r3, -(sp)
	mov	r4, -(sp)
	mov	r5, -(sp)
	mov	@$m_pptr, r0		/ r0 -> текущая нота
	mov	$0177716, r5		/ r5 = регистр динамика
	mov	02(r0), r1		/ r1 = период голоса 1
	mov	04(r0), r2		/ r2 = период голоса 2
	mov	06(r0), r3		/ r3 = период голоса 3
	mov	010(r0), @$m_pdur	/ длительность ноты
1:	mov	$0400, r4		/ внешний цикл 256
2:	dec	r1			/ --- голос 1 ---
	bgt	3f
	mov	@$spk_on,  (r5)
	mov	02(r0), r1
	dec	r3
	dec	r2
	mov	@$spk_off, (r5)
3:	dec	r2			/ --- голос 2 ---
	bgt	4f
	mov	@$spk_on,  (r5)
	mov	04(r0), r2
	dec	r1
	dec	r3
	mov	@$spk_off, (r5)
4:	dec	r3			/ --- голос 3 ---
	bgt	5f
	mov	@$spk_on,  (r5)
	mov	06(r0), r3
	dec	r1
	dec	r2
	mov	@$spk_off, (r5)
5:	sob	r4, 2b
	dec	@$m_pdur		/ длительность--
	bne	1b
	add	$010, @$m_pptr		/ к следующей ноте (запись 8 байт)
	mov	@$m_pptr, r0
	tst	02(r0)			/ терминатор?
	bne	6f
	mov	$pop_data, @$m_pptr	/ да -> зациклить мелодию
6:	mov	(sp)+, r5
	mov	(sp)+, r4
	mov	(sp)+, r3
	mov	(sp)+, r2
	mov	(sp)+, r1
	mov	(sp)+, r0
	rts	pc

	.data
	.even
m_pptr:		.word	pop_data	/ указатель на текущую ноту
m_pdur:		.word	0		/ счётчик длительности ноты
spk_on:		.word	0320		/ динамик ВКЛ (ориг. @#0102064)
spk_off:	.word	0220		/ динамик ВЫКЛ (ориг. @#0102076)

